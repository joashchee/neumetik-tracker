/// The patches, by name.
pub static PRESETS: PresetList = PresetList;

pub struct PresetList;

impl std::ops::Deref for PresetList {
    type Target = [(&'static str, Patch)];
    fn deref(&self) -> &Self::Target {
        static P: OnceLock<Vec<(&'static str, Patch)>> = OnceLock::new();
        P.get_or_init(|| BYTES.iter().map(|(n, b)| (*n, Patch::from_s3m(b))).collect())
    }
}

#[cfg(test)]
mod tests {
    use super::super::FmVoice;
    use super::*;

    #[test]
    fn every_preset_sounds_and_stays_in_range() {
        for (name, patch) in PRESETS.iter() {
            let mut v = FmVoice::new(*patch, 44_100);
            v.key_on(261.63);
            let x: Vec<f32> = (0..22_050).map(|_| v.next()).collect();
            let peak = x.iter().fold(0f32, |a, &b| a.max(b.abs()));
            assert!(peak > 0.02 && peak <= 2.0, "{name}: {peak}");
        }
    }
}
