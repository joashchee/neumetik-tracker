//! SHA-256 (FIPS 180-4), for the repository's IDs: a waveform's, a
//! sample's or a module's ID is the hash of what it is, so the same
//! sample gets the same ID in every repository, and two repositories
//! merge without their IDs ever colliding.
//!
//! And MD5 (RFC 1321, Rivest, 1992), only to compare files with the
//! archives that list theirs by it (Modland's index): never for an ID.

